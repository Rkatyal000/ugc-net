def clean(text):
    out = []
    for ln in text.splitlines():
        s = ln.strip()
        if not s or s.startswith("UGC-NET December") or re.fullmatch(r"Page \d+", s):
            continue
        out.append(s)
    return out

def parse(path, sections, n):
    lines = clean(open(path).read())
    qstart = lines.index("QUESTION PAPER") + 1
    kstart = lines.index("ANSWER KEY")
    estart = lines.index("ANSWER EXPLANATIONS")
    qs, cur, field = {}, None, None
    for s in lines[qstart:kstart]:
        m = re.match(r"Q(\d+)\.\s*(.*)", s)
        o = re.match(r"([A-D])\.\s*(.*)", s)
        if m:
            cur = {"n": int(m.group(1)), "q": m.group(2), "opts": {}}
            qs[cur["n"]] = cur; field = "q"
        elif o and cur is not None:
            field = o.group(1); cur["opts"][field] = o.group(2)
        elif cur is not None:  # wrapped line
            if field == "q": cur["q"] += " " + s
            else: cur["opts"][field] += " " + s
    key = dict((int(a), b) for a, b in re.findall(r"(\d+)\.\s*([A-D])", " ".join(lines[kstart + 1:estart])))
    expl, cur = {}, None
    for s in lines[estart + 1:]:
        m = re.match(r"Q(\d+)\s*—\s*([A-D])\.", s)
        if m:
            cur = int(m.group(1)); expl[cur] = ""
            if key[cur] != m.group(2): sys.exit(f"{path}: key mismatch Q{cur}")
        elif cur is not None:
            expl[cur] = (expl[cur] + " " + s).strip()
    sec_of = {q: name for name, qn in sections.items() for q in qn}
    assert sorted(sec_of) == list(range(1, n + 1)), "section map incomplete"
    assert len(qs) == n and len(key) == n and len(expl) == n, (len(qs), len(key), len(expl))
    res = []
    for i in range(1, n + 1):
        q = qs[i]
        assert list(q["opts"]) == ["A", "B", "C", "D"], i
        res.append({"n": i, "section": sec_of[i], "q": q["q"],
                    "options": [q["opts"][k] for k in "ABCD"],
                    "answer": "ABCD".index(key[i]), "explanation": expl[i]})
    return res

p1 = parse(sys.argv[1], P1_SECTIONS, 50)
p2 = parse(sys.argv[2], P2_SECTIONS, 100)
